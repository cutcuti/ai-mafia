import { writeFileSync } from 'node:fs';
import { MODELS, type ModelSpec } from '@ai-mafia/agents';
import { RANDOM } from './runner.ts';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** supabase/seed.sql: the model registry (+ the random baseline), upserted. Generated — edit models.config.ts instead. */
export function seedSql(models: readonly ModelSpec[] = MODELS): string {
  const rows = [
    { id: RANDOM, provider: 'none', model: 'random', displayName: 'Random (baseline)', pricing: { inputPerMTok: 0, outputPerMTok: 0 }, enabled: true },
    ...models,
  ].map((m) => `  (${q(m.id)}, ${q(m.provider)}, ${q(m.model)}, ${q(m.displayName)}, ${q(JSON.stringify(m.pricing))}::jsonb, ${m.enabled})`);
  return `-- GENERATED by \`pnpm db:gen-seed\` from packages/agents/src/models.config.ts — do not edit by hand.
insert into public.models (id, provider, model, display_name, pricing, enabled) values
${rows.join(',\n')}
on conflict (id) do update
  set provider = excluded.provider, model = excluded.model, display_name = excluded.display_name,
      pricing = excluded.pricing, enabled = excluded.enabled;
`;
}

export const SEED_PATH = new URL('../../../supabase/seed.sql', import.meta.url);

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(SEED_PATH, seedSql());
  console.log(`wrote ${SEED_PATH.pathname}`);
}
